const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

/** Stable id matching the hub's model page URLs, e.g. "anthropic/claude-haiku-4-5" */
export const toModelId = (m: Pick<CatalogModel, 'provider' | 'model'>) => `${slug(m.provider)}/${slug(m.model)}`;

/**
 * ModelParams patch produced when a catalog model is selected.
 * Undefined values intentionally overwrite stale cache/batch prices from a previous selection.
 */
export const catalogModelToParams = (m: CatalogModel, pricedAt: string): Partial<ModelParams> => ({
  modelId: toModelId(m),
  modelName: m.model,
  provider: m.provider,
  pricedAt,
  pricePer1MInputTokens: m.inputPricePer1M,
  pricePer1MOutputTokens: m.outputPricePer1M,
  cachedInputPricePer1M: m.cachedInputPricePer1M,
  batchInputPricePer1M: m.batchInputPricePer1M,
  batchOutputPricePer1M: m.batchOutputPricePer1M,
  useCallPricing: false,
});

/**
 * Refresh one model's prices against the catalog, keeping everything the user owns
 * (token counts, call pricing). Returns the same object reference when nothing changed,
 * so callers can skip React state updates.
 *
 * Custom-priced models (no modelId) and models that have left the catalog are never touched.
 */
export const repriceModelParams = (model: ModelParams, catalog: ModelCatalog): ModelParams => {
  if (!model.modelId) return model;
  const match = catalog.models.find(m => toModelId(m) === model.modelId);
  if (!match) return model;

  const next: ModelParams = {
    ...model,
    modelName: match.model,
    provider: match.provider,
    pricedAt: catalog.pricedAt,
    pricePer1MInputTokens: match.inputPricePer1M,
    pricePer1MOutputTokens: match.outputPricePer1M,
    cachedInputPricePer1M: match.cachedInputPricePer1M,
    batchInputPricePer1M: match.batchInputPricePer1M,
    batchOutputPricePer1M: match.batchOutputPricePer1M,
  };

  const unchanged =
    model.pricePer1MInputTokens === next.pricePer1MInputTokens &&
    model.pricePer1MOutputTokens === next.pricePer1MOutputTokens &&
    model.cachedInputPricePer1M === next.cachedInputPricePer1M &&
    model.batchInputPricePer1M === next.batchInputPricePer1M &&
    model.batchOutputPricePer1M === next.batchOutputPricePer1M &&
    model.pricedAt === next.pricedAt;

  return unchanged ? model : next;
};

/** Reprice both model slots. Returns the same inputs reference when neither changed. */
export const repriceModels = <T extends { primaryModel: ModelParams; secondaryModel: ModelParams }>(
  inputs: T,
  catalog: ModelCatalog
): T => {
  const primaryModel = repriceModelParams(inputs.primaryModel, catalog);
  const secondaryModel = repriceModelParams(inputs.secondaryModel, catalog);
  if (primaryModel === inputs.primaryModel && secondaryModel === inputs.secondaryModel) return inputs;
  return { ...inputs, primaryModel, secondaryModel };
};

/** Build preset ModelParams from the embedded snapshot. Throws at module init if the model is missing. */
export const presetModel = (
  provider: string,
  model: string,
  avgInputTokensPerUnit: number,
  avgOutputTokensPerUnit: number
): ModelParams => {
  const found = SNAPSHOT_MODELS.find(m => m.provider === provider && m.model === model);
  if (!found) {
    throw new Error(`presetModel: "${provider} / ${model}" not found in the embedded model snapshot`);
  }
  return {
    avgInputTokensPerUnit,
    avgOutputTokensPerUnit,
    costPerCall: 0.005,
    useCallPricing: false,
    ...catalogModelToParams(found, SNAPSHOT_DATE),
  } as ModelParams;
};

const isValidModel = (m: any): m is CatalogModel =>
  m &&
  typeof m.provider === 'string' &&
  typeof m.model === 'string' &&
  typeof m.inputPricePer1M === 'number' &&
  typeof m.outputPricePer1M === 'number' &&
  m.inputPricePer1M >= 0 &&
  m.outputPricePer1M >= 0;

/**
 * Sort by ELO and drop entries that collapse to the same model id. Distinct catalog
 * rows can slugify identically (e.g. a duplicated provider/model pair), which would
 * make repricing ambiguous and duplicate React keys in the picker. Highest ELO wins.
 */
const sortAndDedupe = (models: CatalogModel[]): CatalogModel[] => {
  const seen = new Set<string>();
  return [...models]
    .sort((a, b) => (b.eloScore ?? 0) - (a.eloScore ?? 0))
    .filter(m => {
      const id = toModelId(m);
      if (seen.has(id)) return false;
      seen.add(id);
      return true;
    });
};

const snapshotCatalog = (): ModelCatalog => ({
  models: sortAndDedupe(SNAPSHOT_MODELS),
  source: 'snapshot',
  pricedAt: SNAPSHOT_DATE,
});

interface StoredCatalog {
  fetchedAt: number;
  pricedAt: string;
  models: CatalogModel[];
}

/**
 * This module is shared verbatim with the MCP server, which runs under Node where
 * there is no localStorage. Absence just means no cache layer — the live fetch and
 * the embedded snapshot still work.
 */
const storage = (): Storage | null => {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage;
  } catch {
    return null; // access can throw outright when storage is blocked by policy
  }
};

const readStoredCatalog = (): StoredCatalog | null => {
  try {
    const store = storage();
    if (!store) return null;
    const raw = store.getItem(STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed.models)) return null;
    // Shape-check every entry, exactly as the API path does. localStorage is as
    // untrusted as the network: a model whose prices came back as strings would be
    // repriced onto the form by repriceModels() and turn every cost metric into NaN,
    // and the cache would keep serving it for the next 24 hours.
    const models = parsed.models.filter(isValidModel);
    if (models.length < MIN_MODELS) return null;
    return { ...parsed, models };
  } catch {
    return null;
  }
};

/** Try each endpoint in turn; throws only if all of them fail. */
const fetchFirstAvailable = async (): Promise<any> => {
  let lastError: unknown;
  for (const url of API_URLS) {
    try {
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
      try {
        const response = await fetch(url, { signal: controller.signal });
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        return await response.json();
      } finally {
        clearTimeout(timer);
      }
    } catch (error) {
      lastError = error;
    }
  }
  throw lastError ?? new Error('no pricing endpoint reachable');
};

/**
 * Resolve the model catalog: fresh localStorage cache first, then the live hub API,
 * then a stale cache, then the embedded snapshot. Never rejects.
 */
export const fetchModelCatalog = async (forceRefresh = false): Promise<ModelCatalog> => {
  const stored = readStoredCatalog();
  if (!forceRefresh && stored && Date.now() - stored.fetchedAt < CACHE_TTL_MS) {
    return { models: sortAndDedupe(stored.models), source: 'cache', pricedAt: stored.pricedAt };
  }

  try {
    const data = await fetchFirstAvailable();
    const models: CatalogModel[] = (Array.isArray(data.models) ? data.models : [])
      .filter(isValidModel)
      .map((m: CatalogModel) => ({
        provider: m.provider,
        model: m.model,
        inputPricePer1M: m.inputPricePer1M,
        outputPricePer1M: m.outputPricePer1M,
        batchInputPricePer1M: m.batchInputPricePer1M,
        batchOutputPricePer1M: m.batchOutputPricePer1M,
        cachedInputPricePer1M: m.cachedInputPricePer1M,
        contextWindow: m.contextWindow,
        category: m.category,
        eloScore: m.eloScore,
        releaseDate: m.releaseDate,
      }));
    if (models.length < MIN_MODELS) throw new Error(`only ${models.length} models returned`);

    const pricedAt = typeof data.meta?.timestamp === 'string' ? data.meta.timestamp : new Date().toISOString();
    try {
      storage()?.setItem(STORAGE_KEY, JSON.stringify({ fetchedAt: Date.now(), pricedAt, models }));
    } catch {
      // storage full or unavailable — live data still usable
    }
    return { models: sortAndDedupe(models), source: 'live', pricedAt };
  } catch {
    if (stored) {
      return { models: sortAndDedupe(stored.models), source: 'cache', pricedAt: stored.pricedAt };
    }
    return snapshotCatalog();
  }
};
